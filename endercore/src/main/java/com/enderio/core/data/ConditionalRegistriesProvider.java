package com.enderio.core.data;

import com.enderio.core.data.recipe.RecipeOutput;
import com.google.common.hash.Hashing;
import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import com.google.gson.JsonParser;
import net.minecraft.core.HolderLookup;
import net.minecraft.core.RegistrySetBuilder;
import net.minecraft.data.CachedOutput;
import net.minecraft.data.PackOutput;
import net.minecraft.resources.ResourceKey;
import net.minecraftforge.common.ForgeHooks;
import net.minecraftforge.common.crafting.conditions.ICondition;
import net.minecraftforge.common.data.DatapackBuiltinEntriesProvider;

import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;
import java.util.concurrent.CompletableFuture;

/** Attaches native Forge registry conditions before the generated bytes enter the output cache. */
public final class ConditionalRegistriesProvider extends DatapackBuiltinEntriesProvider {
    private static final Gson GSON = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().create();
    private final Map<Path, ICondition> conditions;
    private final String name;

    public ConditionalRegistriesProvider(PackOutput output, CompletableFuture<HolderLookup.Provider> registries,
            RegistrySetBuilder builder, Set<String> namespaces, Map<ResourceKey<?>, ICondition> conditions, String name) {
        super(output, registries, builder, namespaces);
        this.name = name;
        var paths = new HashMap<Path, ICondition>();
        conditions.forEach((key, condition) -> paths.put(output.createPathProvider(PackOutput.Target.DATA_PACK,
            ForgeHooks.prefixNamespace(key.registry())).json(key.location()), condition));
        this.conditions = Map.copyOf(paths);
    }

    @Override
    public CompletableFuture<?> run(CachedOutput output) {
        return super.run((path, bytes, hash) -> {
            var condition = conditions.get(path);
            if (condition != null) {
                var json = JsonParser.parseString(new String(bytes, StandardCharsets.UTF_8)).getAsJsonObject();
                RecipeOutput.appendConditions(json, "forge:conditions", condition);
                bytes = GSON.toJson(json).getBytes(StandardCharsets.UTF_8);
                hash = Hashing.sha1().hashBytes(bytes);
            }
            output.writeIfNeeded(path, bytes, hash);
        });
    }

    @Override
    public String getName() {
        return name;
    }
}
